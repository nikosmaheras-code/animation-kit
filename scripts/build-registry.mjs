#!/usr/bin/env node
// Build the registry from per-skill skill.json files.
//   node scripts/build-registry.mjs            → regenerate registry.json + REGISTRY.md
//   node scripts/build-registry.mjs --check    → validate only, fail (exit 1) on problems
//   node scripts/build-registry.mjs --ids [status]  → print skill ids (optionally filtered by status)
//
// Source of truth = skills/<id>/skill.json. Drop a new skill folder with a skill.json,
// run this, and the registry + index regenerate. Zero dependencies.

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS_DIR = join(ROOT, "skills");
const VALID_STATUS = ["approved", "draft", "experimental", "deprecated"];
const REQUIRED = ["id", "title", "description", "version", "status", "category", "tags", "entry"];

const args = process.argv.slice(2);
const mode = args.find((a) => a.startsWith("--")) || "--build";

function loadSkills() {
  const skills = [];
  const errors = [];
  for (const id of readdirSync(SKILLS_DIR).sort()) {
    const dir = join(SKILLS_DIR, id);
    if (!statSync(dir).isDirectory()) continue;
    const manifest = join(dir, "skill.json");
    if (!existsSync(manifest)) { errors.push(`${id}: missing skill.json`); continue; }
    let s;
    try { s = JSON.parse(readFileSync(manifest, "utf8")); }
    catch (e) { errors.push(`${id}: invalid JSON (${e.message})`); continue; }

    for (const f of REQUIRED) if (s[f] === undefined) errors.push(`${id}: missing required field "${f}"`);
    if (s.id && s.id !== id) errors.push(`${id}: skill.json id "${s.id}" != folder name`);
    if (s.status && !VALID_STATUS.includes(s.status)) errors.push(`${id}: invalid status "${s.status}"`);
    if (s.entry && !existsSync(join(dir, s.entry))) errors.push(`${id}: entry "${s.entry}" not found`);

    const refDir = join(dir, "references");
    const refs = existsSync(refDir) ? readdirSync(refDir).filter((f) => f.endsWith(".md")).sort() : [];
    skills.push({ ...s, path: `skills/${id}`, referenceCount: refs.length, references: refs });
  }
  return { skills, errors };
}

const { skills, errors } = loadSkills();

if (mode === "--ids") {
  const status = args[args.indexOf("--ids") + 1];
  const filtered = status && !status.startsWith("--") ? skills.filter((s) => s.status === status) : skills;
  console.log(filtered.map((s) => s.id).join("\n"));
  process.exit(0);
}

if (errors.length) {
  console.error("Registry validation failed:\n" + errors.map((e) => "  - " + e).join("\n"));
  process.exit(1);
}
if (mode === "--check") {
  console.log(`OK — ${skills.length} skill(s) valid.`);
  process.exit(0);
}

// --build: regenerate registry.json + REGISTRY.md
const registry = {
  name: "Animation Kit",
  description: "A curated Claude Code skills registry for motion & animation.",
  generated: "by scripts/build-registry.mjs — do not edit by hand",
  skillCount: skills.length,
  skills: skills.map(({ references, ...rest }) => rest),
};
writeFileSync(join(ROOT, "registry.json"), JSON.stringify(registry, null, 2) + "\n");

const badge = { approved: "✅ approved", draft: "📝 draft", experimental: "🧪 experimental", deprecated: "⚠️ deprecated" };
const rows = skills
  .map((s) => `| [\`${s.id}\`](${s.path}/) | ${s.title} | ${badge[s.status] || s.status} | v${s.version} | ${s.referenceCount} | ${(s.tags || []).join(", ")} |`)
  .join("\n");

const md = `# Registry

> Generated by \`scripts/build-registry.mjs\` from each skill's \`skill.json\`. Do not edit by hand —
> add/update a skill's \`skill.json\` and re-run the script.

**${skills.length} skill(s)** · ${skills.filter((s) => s.status === "approved").length} approved

| Skill | Title | Status | Version | Refs | Tags |
|---|---|---|---|---|---|
${rows}

## Status meaning
- **✅ approved** — verified against its sources, complete (SKILL.md + references), safe to share/install.
- **📝 draft** — in progress, not yet vetted.
- **🧪 experimental** — usable but unstable; API/structure may change.
- **⚠️ deprecated** — kept for reference; prefer a successor.

Only \`approved\` skills install by default (\`./scripts/install.sh\`).
`;
writeFileSync(join(ROOT, "REGISTRY.md"), md);
console.log(`Wrote registry.json + REGISTRY.md (${skills.length} skills).`);
